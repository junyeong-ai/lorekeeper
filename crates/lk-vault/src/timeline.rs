//! Wiki timeline (`log.md`) — a deterministic, reverse-chronological view of each
//! knowledge page's declared `created` date, which may be its source's authored date.
//!
//! This is Karpathy's append-only `log.md`, realized the Lorekeeper way: a MATERIALIZED
//! VIEW, not a hand-appended file. It is regenerated from each page's frontmatter, so an
//! unchanged vault re-renders byte-identical (like `index.md`) and a re-run is a true
//! no-op — it can never drift, duplicate, or lose an entry. It complements `index.md`
//! (the by-topic catalog) with a by-created-date view, not an ingestion history.
//!
//! Two deliberate design rules keep the signal meaningful:
//!
//! 1. **Anchored on `created` ONLY, never `updated`.** A concept's `updated` is its
//!    last-observation date — it churns every time the concept is re-mentioned, and
//!    machine work (ingest re-render, `backlinks-sync`) can touch it. Keying a knowledge
//!    timeline off `updated` would inject that churn as fake "knowledge changed" events.
//!    `created` is the recorded date anchor; it does not establish collection time.
//! 2. **Durable knowledge nodes only** — `{wiki}/concepts`, `{wiki}/documents`,
//!    `{wiki}/explorations`. Daily/synthesis pages are time-stamped operational records,
//!    not knowledge nodes. This is a principled classification, not a fuzzy
//!    importance/activity score (which would be a heuristic).
//!
//! Every dated durable knowledge node remains reachable. Large timelines expose bounded
//! detail pages under the catalog namespace rather than an ever-growing entry page.

use std::collections::{BTreeMap, HashSet};
use std::path::{Path, PathBuf};

use lk_core::config::VaultDirs;
use lk_core::i18n::Locale;
use lk_core::vault_path::{concepts_dir, documents_dir, explorations_dir};

use crate::{MutationSession, NavigationCatalog, NavigationKind, NavigationRow, VaultError};

struct TimelineEntry {
    /// The declared frontmatter `created` date, not a measured collection time.
    created: jiff::civil::Date,
    /// Vault-relative page path — the link destination is computed from it, relative
    /// to the timeline's own location (`{wiki}/log.md`).
    path: std::path::PathBuf,
    /// Display title.
    title: String,
}

/// Build the entry-page body of the complete timeline. Publish `build_timeline_catalog`
/// when writing, so its bounded detail pages are included. A pure function of on-disk
/// frontmatter — re-running on an unchanged vault yields identical bytes. Pages missing
/// a parseable `created` date are skipped (they have no place on a timeline), never guessed.
pub fn build_timeline(
    vault_root: &Path,
    locale: Locale,
    dirs: &VaultDirs,
) -> Result<String, VaultError> {
    let catalog = build_timeline_catalog(vault_root, locale, dirs)?;
    Ok(catalog.pages[&Path::new(&dirs.wiki).join(lk_core::vault_path::TIMELINE_FILE)].clone())
}

/// Build the complete bounded timeline, including every generated detail page.
pub fn build_timeline_catalog(
    vault_root: &Path,
    locale: Locale,
    dirs: &VaultDirs,
) -> Result<NavigationCatalog, VaultError> {
    let mut entries: Vec<TimelineEntry> = Vec::new();
    let mut seen: HashSet<PathBuf> = HashSet::new();
    for dir in [
        concepts_dir(dirs),
        documents_dir(dirs),
        explorations_dir(dirs),
    ] {
        collect_into(&mut entries, vault_root, &dir, &mut seen)?;
    }

    // Group by created date. BTreeMap keeps dates ascending; we emit descending so the
    // newest knowledge is first. Within a date, entries sort by title then id — a stable,
    // deterministic render.
    let shown = entries.len();
    let mut by_date: BTreeMap<jiff::civil::Date, Vec<TimelineEntry>> = BTreeMap::new();
    for e in entries {
        by_date.entry(e.created).or_default().push(e);
    }

    let title = locale.strings().log_title;
    let basis = match locale {
        Locale::Ko => "`created` 기준 · 원문 작성일일 수 있으며 수집 시각이 아닙니다.",
        Locale::En => {
            "By declared `created`; may be the source's authored date, not collection time."
        }
    };
    let header =
        format!("# {title}\n\n> Generated by `lore wiki log` — {shown} entries.\n> {basis}\n");
    let mut rows = Vec::with_capacity(shown);
    for (date, mut day_entries) in by_date.into_iter().rev() {
        day_entries.sort_by(|a, b| a.title.cmp(&b.title).then_with(|| a.path.cmp(&b.path)));
        for entry in day_entries {
            rows.push(NavigationRow {
                headings: vec![date.to_string().into()],
                title: entry.title,
                path: entry.path,
                summary: None,
            });
        }
    }
    Ok(NavigationCatalog::build(
        NavigationKind::Timeline,
        Path::new(&dirs.wiki),
        title,
        &header,
        rows,
    ))
}

/// Publish the complete timeline through the caller's cooperating writer session.
/// Returns the absolute entry-page address, as `write_index` does.
pub fn write_timeline(
    session: &MutationSession,
    locale: Locale,
    dirs: &VaultDirs,
) -> Result<PathBuf, VaultError> {
    let catalog = build_timeline_catalog(session.root(), locale, dirs)?;
    catalog.publish(session)?;
    Ok(session
        .root()
        .join(&dirs.wiki)
        .join(lk_core::vault_path::TIMELINE_FILE))
}

/// The page formats this timeline is a timeline OF — one per directory it walks. A subset of
/// [`lk_core::vault_path::PAGE_FORMATS`], asserted so a typo here cannot silently drop a whole
/// format off the timeline.
const KNOWLEDGE_FORMATS: &[&str] = &["concept", "document", "exploration"];

/// Walk one knowledge directory, parsing each page's `created`/`title` into a [`TimelineEntry`].
/// Undated pages are skipped; traversal, read and parse failures abort publication.
///
/// `seen` carries canonical page identity across the three directories. All three sit under
/// `wiki`, which reads like enough — but a `vault.dirs` root the filesystem folds onto another
/// puts a daily page inside one of them, and the timeline promises durable knowledge nodes
/// only. It was reached that way: a daily digest became a permanent entry in the knowledge
/// timeline, which is the one thing this file says it will not do.
fn collect_into(
    entries: &mut Vec<TimelineEntry>,
    vault_root: &Path,
    rel_dir: &Path,
    seen: &mut HashSet<PathBuf>,
) -> Result<(), VaultError> {
    let abs = vault_root.join(rel_dir);
    for path in crate::search::markdown_files(vault_root, &abs)? {
        if !seen.insert(std::fs::canonicalize(&path)?) {
            continue;
        }
        let page = crate::store::read_page(vault_root, &path)?;
        // The three directories walked here hold the three durable knowledge formats, and a
        // page declaring any other one is foreign to them however it arrived — a `vault.dirs`
        // root the filesystem folds onto another lands a daily digest inside `wiki/concepts`,
        // and this file promises knowledge nodes only. Directory membership was the whole test
        // before, which made that promise depend on nothing checkable. A page declaring no
        // type at all predates the field and stays: the check names what is foreign, not what
        // is permitted.
        if page
            .frontmatter
            .get("type")
            .and_then(|value| value.as_str())
            .is_some_and(|declared| !KNOWLEDGE_FORMATS.contains(&declared))
        {
            continue;
        }
        let Some(created) = fm_date(&page, "created") else {
            continue;
        };
        let rel = path
            .strip_prefix(vault_root)
            .map_err(std::io::Error::other)?;
        let title = page
            .frontmatter
            .get("title")
            .and_then(|v| v.as_str())
            .filter(|s| !s.is_empty())
            .map(str::to_owned)
            .unwrap_or_else(|| {
                path.file_stem()
                    .and_then(|s| s.to_str())
                    .unwrap_or("untitled")
                    .to_owned()
            });
        entries.push(TimelineEntry {
            created,
            path: rel.to_path_buf(),
            title,
        });
    }
    Ok(())
}

fn fm_date(page: &lk_core::frontmatter::VaultPage, key: &str) -> Option<jiff::civil::Date> {
    page.frontmatter
        .get(key)
        .and_then(|v| v.as_str())
        .and_then(|s| s.parse::<jiff::civil::Date>().ok())
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    /// Which formats are durable knowledge is a judgement this file makes, but that they are
    /// formats this tool writes at all is not — and a typo here does not fail anything on its
    /// own. It reads as "no page of that format is a knowledge node", so the whole format drops
    /// off the timeline silently.
    #[test]
    fn every_knowledge_format_is_a_format_this_tool_writes() {
        for format in KNOWLEDGE_FORMATS {
            assert!(
                lk_core::vault_path::PAGE_FORMATS.contains(format),
                "{format:?} is not a page format Lorekeeper writes"
            );
        }
    }

    fn write(root: &Path, rel: &str, body: &str) {
        let p = root.join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, body).unwrap();
    }

    fn concept(root: &Path, slug: &str, title: &str, created: &str) {
        write(
            root,
            &format!("wiki/concepts/{slug}.md"),
            &format!("---\nid: {slug}\ntitle: {title}\ncreated: {created}\n---\n"),
        );
    }

    /// The timeline is a timeline of durable knowledge, and directory membership was the whole
    /// test — so an operational record that landed in one of these directories became a
    /// permanent knowledge entry. It lands there when a `vault.dirs` root the filesystem folds
    /// puts `<daily>` inside `wiki`. A page declaring no type predates the field and stays,
    /// since the check names what is foreign rather than what is permitted.
    #[test]
    fn an_operational_record_inside_a_knowledge_directory_is_not_a_knowledge_node() {
        let tmp = TempDir::new().unwrap();
        write(
            tmp.path(),
            "wiki/concepts/2026-02-10.md",
            "---\nid: d\ntype: daily\ntitle: Digest\ncreated: 2026-02-10\n---\n",
        );
        write(
            tmp.path(),
            "wiki/concepts/rag.md",
            "---\nid: rag\ntype: concept\ntitle: RAG\ncreated: 2026-02-11\n---\n",
        );
        // No `type` at all: a page from before the field, which must not be dropped.
        write(
            tmp.path(),
            "wiki/documents/old.md",
            "---\nid: old\ntitle: Old\ncreated: 2026-02-12\n---\n",
        );

        let out = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert!(
            !out.contains("Digest"),
            "a daily record is not knowledge:\n{out}"
        );
        assert!(out.contains("RAG"), "{out}");
        assert!(out.contains("Old"), "an untyped page stays:\n{out}");
    }

    #[test]
    fn timeline_is_reverse_chronological_and_navigable() {
        let tmp = TempDir::new().unwrap();
        let dirs = VaultDirs::default();
        concept(tmp.path(), "rag", "RAG", "2026-05-20");
        concept(tmp.path(), "embeddings", "Embeddings", "2026-05-22");
        write(
            tmp.path(),
            "wiki/documents/report.md",
            "---\nid: report\ntitle: Report\ncreated: 2026-05-20\n---\n",
        );

        let out = build_timeline(tmp.path(), Locale::Ko, &dirs).unwrap();
        let h22 = out.find("## 2026-05-22").unwrap();
        let h20 = out.find("## 2026-05-20").unwrap();
        assert!(h22 < h20, "newer date must come first:\n{out}");
        assert!(out.contains("3 entries"));
        assert!(out.contains("- [Embeddings](concepts/embeddings.md)"));
        assert!(out.contains("- [Report](documents/report.md)"));
    }

    #[test]
    fn timeline_anchors_on_created_not_updated() {
        // `updated` churn (re-mention / machine re-render) must NOT move an entry or add
        // a noise annotation — the timeline is keyed on first-appearance only.
        let tmp = TempDir::new().unwrap();
        write(
            tmp.path(),
            "wiki/concepts/rag.md",
            "---\nid: rag\ntitle: RAG\ncreated: 2026-05-20\nupdated: 2026-09-01\n---\n",
        );
        let out = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert!(out.contains("## 2026-05-20"), "must be placed by created");
        assert!(
            !out.contains("2026-09-01"),
            "updated must not appear anywhere"
        );
        assert!(!out.contains("updated"), "no updated annotation");
    }

    #[test]
    fn timeline_is_complete_regardless_of_age() {
        // Every durable knowledge node appears, however old — the timeline is a complete
        // by-time view (as `index.md` is a complete by-topic view), never truncated. The
        // long-term evolution of the vault is exactly what this view exists to show.
        let tmp = TempDir::new().unwrap();
        concept(tmp.path(), "ancient", "Ancient", "2020-01-01");
        concept(tmp.path(), "recent", "Recent", "2026-05-20");
        let out = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert!(out.contains("[Recent]("), "recent entry shown");
        assert!(
            out.contains("[Ancient]("),
            "years-old entry shown — never truncated"
        );
        assert!(out.contains("2 entries"));
        // Newest date first, oldest last — reverse chronological across any span.
        let h_recent = out.find("## 2026-05-20").unwrap();
        let h_ancient = out.find("## 2020-01-01").unwrap();
        assert!(h_recent < h_ancient, "reverse chronological:\n{out}");
    }

    #[test]
    fn undated_pages_skipped_and_render_is_deterministic() {
        let tmp = TempDir::new().unwrap();
        write(
            tmp.path(),
            "wiki/concepts/x.md",
            "---\nid: x\ntitle: X\n---\n",
        ); // no created
        concept(tmp.path(), "y", "Y", "2026-05-20");
        let first = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        let second = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert_eq!(first, second, "build must be deterministic");
        assert!(first.contains("1 entries"));
        assert!(!first.contains("[X]("), "undated page must be skipped");
    }

    #[test]
    fn empty_vault_yields_just_the_header() {
        let tmp = TempDir::new().unwrap();
        let out = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert!(out.contains("# 지식 로그"));
        assert!(out.contains("0 entries"));
    }

    /// The returned path is what `lore wiki log` prints as the file it wrote, so it has to be
    /// that file: the timeline landing somewhere else while the command reported success is
    /// indistinguishable from working, and the reserved name is what the graph excludes.
    #[test]
    fn the_timeline_is_written_where_the_returned_path_says() {
        let tmp = TempDir::new().unwrap();
        let dirs = VaultDirs::default();
        concept(tmp.path(), "y", "Y", "2026-05-20");

        let session = MutationSession::acquire(tmp.path()).unwrap();
        let written = write_timeline(&session, Locale::Ko, &dirs).unwrap();
        assert_eq!(
            written,
            tmp.path()
                .join(&dirs.wiki)
                .join(lk_core::vault_path::TIMELINE_FILE)
                .canonicalize()
                .unwrap()
        );
        assert_eq!(
            std::fs::read_to_string(&written).unwrap(),
            build_timeline(tmp.path(), Locale::Ko, &dirs).unwrap()
        );
    }

    #[test]
    fn timeline_h1_is_localized() {
        let tmp = TempDir::new().unwrap();
        let en = build_timeline(tmp.path(), Locale::En, &VaultDirs::default()).unwrap();
        assert!(en.contains("# Knowledge Log"), "EN H1 localized:\n{en}");
        let ko = build_timeline(tmp.path(), Locale::Ko, &VaultDirs::default()).unwrap();
        assert!(ko.contains("# 지식 로그"), "KO H1 localized:\n{ko}");
        assert!(ko.contains("수집 시각이 아닙니다"));
        assert!(en.contains("not collection time"));
    }

    #[test]
    fn neighboring_days_do_not_share_a_detail_page() {
        let tmp = TempDir::new().unwrap();
        for (day, date) in [("newer", "2026-05-20"), ("older", "2026-05-19")] {
            for number in 0..60 {
                concept(tmp.path(), &format!("{day}-{number}"), "Entry", date);
            }
        }
        let catalog =
            build_timeline_catalog(tmp.path(), Locale::En, &VaultDirs::default()).unwrap();
        let root = &catalog.pages[Path::new("wiki/log.md")];
        assert!(root.contains("[2026-05-20 (60)]"), "{root}");
        assert!(root.contains("[2026-05-19 (60)]"), "{root}");
        for (path, content) in &catalog.pages {
            if path != Path::new("wiki/log.md") {
                assert_ne!(
                    content.contains("## 2026-05-20"),
                    content.contains("## 2026-05-19")
                );
            }
        }
    }

    #[test]
    fn a_busy_day_is_split_without_losing_its_date_or_destinations() {
        let tmp = TempDir::new().unwrap();
        let dirs = VaultDirs::default();
        for number in 0..101 {
            concept(
                tmp.path(),
                &format!("item-{number}"),
                &format!("Item {number:03}"),
                "2026-05-20",
            );
        }
        for locale in [Locale::Ko, Locale::En] {
            let catalog = build_timeline_catalog(tmp.path(), locale, &dirs).unwrap();
            assert_eq!(catalog.pages.len(), 3);
            let root = &catalog.pages[Path::new("wiki/log.md")];
            assert!(root.contains(locale.strings().log_title));
            assert!(root.contains("101 entries"));
            let mut destinations = HashSet::new();
            for (path, content) in &catalog.pages {
                if path == Path::new("wiki/log.md") {
                    continue;
                }
                assert!(content.contains("## 2026-05-20"));
                for dest in lk_core::link::extract_dests(content) {
                    let target = lk_core::link::resolve_dest(path, &dest).unwrap();
                    if target != Path::new("wiki/log.md") {
                        assert!(destinations.insert(target));
                    }
                }
            }
            assert_eq!(destinations.len(), 101);
        }
    }

    #[test]
    fn incomplete_inputs_leave_the_published_timeline_untouched() {
        let tmp = TempDir::new().unwrap();
        let dirs = VaultDirs::default();
        concept(tmp.path(), "good", "Good", "2026-05-20");
        let session = MutationSession::acquire(tmp.path()).unwrap();
        let written = write_timeline(&session, Locale::En, &dirs).unwrap();
        let previous = std::fs::read_to_string(&written).unwrap();
        write(tmp.path(), "wiki/concepts/bad.md", "---\ntitle: [\n---\n");
        assert!(write_timeline(&session, Locale::En, &dirs).is_err());
        assert_eq!(std::fs::read_to_string(&written).unwrap(), previous);
        std::fs::remove_file(tmp.path().join("wiki/concepts/bad.md")).unwrap();
        std::fs::write(tmp.path().join("wiki/concepts/bad.md"), [0xff]).unwrap();
        assert!(write_timeline(&session, Locale::En, &dirs).is_err());
        assert_eq!(std::fs::read_to_string(&written).unwrap(), previous);
        std::fs::remove_file(tmp.path().join("wiki/concepts/bad.md")).unwrap();
        std::fs::write(tmp.path().join("wiki/documents"), "not a directory").unwrap();
        assert!(write_timeline(&session, Locale::En, &dirs).is_err());
        assert_eq!(std::fs::read_to_string(&written).unwrap(), previous);
    }
}
